/**
 * fix-expo-gradle.js
 * 
 * 1. Patches expo-modules-core ExpoModulesCorePlugin.gradle to fix:
 *    "Could not get unknown property 'release' for SoftwareComponent container"
 *    This error occurs with AGP 8.7+ where components.release may not exist.
 * 
 * 2. Patches app/build.gradle to add pickFirsts + doNotStrip for .so files
 *    and injects a pure Groovy ELF64 patcher (via doLast on merge/strip tasks)
 *    that rewrites p_align from 4096 → 16384 for all PT_LOAD segments in 64-bit
 *    .so files. No external tools (NDK llvm-objcopy, patchelf) needed.
 */

const fs = require('fs');
const path = require('path');

function patchBuildGradleFor16KB() {
  // Find app/build.gradle in the current app directory
  const possiblePaths = [
    path.resolve(process.cwd(), 'android', 'app', 'build.gradle'),
    path.resolve(__dirname, '..', 'apps', 'customer-app', 'android', 'app', 'build.gradle'),
    path.resolve(__dirname, '..', 'apps', 'partners-app', 'android', 'app', 'build.gradle'),
  ];

  let filePath = null;
  for (const p of possiblePaths) {
    if (fs.existsSync(p)) {
      filePath = p;
      break;
    }
  }

  if (!filePath) {
    console.log('[fix-expo-gradle] app/build.gradle not found, skipping 16KB patch');
    return;
  }

  let content = fs.readFileSync(filePath, 'utf8');

  // Check if already patched with both pickFirsts and doNotStrip
  const hasPickFirsts = content.includes("pickFirsts += ['**/libc++_shared.so'");
  const hasDoNotStrip = content.includes("doNotStrip '**/*.so'") || content.includes('doNotStrip "**/*.so"');

  if (hasPickFirsts && hasDoNotStrip) {
    console.log('[fix-expo-gradle] build.gradle already has pickFirsts and doNotStrip, skipping');
    return;
  }

  // The packagingOptions block to find (generated by expo prebuild)
  const oldBlock = `packagingOptions {
        jniLibs {
            useLegacyPackaging (findProperty('expo.useLegacyPackaging')?.toBoolean() ?: false)
        }
    }`;

  const newBlock = `packagingOptions {
        jniLibs {
            useLegacyPackaging (findProperty('expo.useLegacyPackaging')?.toBoolean() ?: false)
        }
        // Force single copy of each native lib — needed for 16KB page alignment on Android 15+
        pickFirsts += ['**/libc++_shared.so', '**/libfbjni.so', '**/libhermes.so', '**/libreactnative.so']
        // Keep .so files uncompressed so AGP can page-align them to 16KB
        doNotStrip '**/*.so'
    }`;

  if (content.includes(oldBlock)) {
    content = content.replace(oldBlock, newBlock);
    fs.writeFileSync(filePath, content, 'utf8');
    console.log('[fix-expo-gradle] Added pickFirsts and doNotStrip for 16KB alignment in', filePath);
  } else {
    // Try a more flexible approach - find any packagingOptions with jniLibs
    const jniLibsPattern = /(packagingOptions\s*\{[\s\S]*?jniLibs\s*\{[\s\S]*?useLegacyPackaging[^}]*\}[\s\S]*?\})/;
    const match = content.match(jniLibsPattern);
    if (match) {
      const oldJniBlock = match[1];
      // Insert pickFirsts and doNotStrip before the closing brace of packagingOptions
      const insertBeforeClose = oldJniBlock.replace(
        /(useLegacyPackaging[^}]*\})\s*\}/,
        "$1\n        // Force single copy of each native lib — needed for 16KB page alignment\n        pickFirsts += ['**/libc++_shared.so', '**/libfbjni.so', '**/libhermes.so', '**/libreactnative.so']\n        doNotStrip '**/*.so'\n    }"
      );
      content = content.replace(oldJniBlock, insertBeforeClose);
      fs.writeFileSync(filePath, content, 'utf8');
      console.log('[fix-expo-gradle] Added pickFirsts and doNotStrip (flexible) in', filePath);
    } else {
      console.log('[fix-expo-gradle] Could not find packagingOptions block in build.gradle');
    }
  }
}

function patchExpoModulesCorePlugin() {
  // Find the ExpoModulesCorePlugin.gradle
  const possiblePaths = [
    path.resolve(__dirname, '..', 'apps', 'customer-app', 'node_modules', 'expo-modules-core', 'android', 'ExpoModulesCorePlugin.gradle'),
    path.resolve(__dirname, '..', 'node_modules', 'expo-modules-core', 'android', 'ExpoModulesCorePlugin.gradle'),
    path.resolve(process.cwd(), 'node_modules', 'expo-modules-core', 'android', 'ExpoModulesCorePlugin.gradle'),
  ];

  let filePath = null;
  for (const p of possiblePaths) {
    if (fs.existsSync(p)) {
      filePath = p;
      break;
    }
  }

  if (!filePath) {
    console.log('[fix-expo-gradle] ExpoModulesCorePlugin.gradle not found, skipping');
    return;
  }

  let content = fs.readFileSync(filePath, 'utf8');

  // Check if already patched
  if (content.includes('components.findByName')) {
    console.log('[fix-expo-gradle] Already patched, skipping');
    return;
  }

  // Replace the problematic publishing block
  const oldBlock = `  project.afterEvaluate {
    publishing {
      publications {
        release(MavenPublication) {
          from components.release
        }
      }
      repositories {
        maven {
          url = mavenLocal().url
        }
      }
    }
  }`;

  const newBlock = `  project.afterEvaluate {
    publishing {
      publications {
        release(MavenPublication) {
          def releaseComponent = components.findByName('release')
          if (releaseComponent) {
            from releaseComponent
          }
        }
      }
      repositories {
        maven {
          url = mavenLocal().url
        }
      }
    }
  }`;

  if (content.includes('from components.release')) {
    content = content.replace('from components.release', 
      "def releaseComponent = components.findByName('release')\n          if (releaseComponent) {\n            from releaseComponent\n          }");
    fs.writeFileSync(filePath, content, 'utf8');
    console.log('[fix-expo-gradle] Patched components.release -> findByName in', filePath);
  } else {
    console.log('[fix-expo-gradle] No patch needed - components.release not found in file');
  }
}

patchBuildGradleFor16KB();
patchExpoModulesCorePlugin();
injectAlignmentTask();
console.log('[fix-expo-gradle] Done');

/**
 * Injects a pure Groovy ELF64 patcher via doLast on merge + strip tasks.
 * This guarantees the patching runs as part of those tasks directly.
 * Also patches after strip tasks (which may re-process .so files).
 * Searches ALL known build intermediate directories.
 */
function injectAlignmentTask() {
  const possiblePaths = [
    path.resolve(process.cwd(), 'android', 'app', 'build.gradle'),
    path.resolve(__dirname, '..', 'apps', 'customer-app', 'android', 'app', 'build.gradle'),
    path.resolve(__dirname, '..', 'apps', 'partners-app', 'android', 'app', 'build.gradle'),
  ];

  let filePath = null;
  for (const p of possiblePaths) {
    if (fs.existsSync(p)) {
      filePath = p;
      break;
    }
  }

  if (!filePath) {
    console.log('[fix-expo-gradle] app/build.gradle not found, skipping alignment task');
    return;
  }

  let content = fs.readFileSync(filePath, 'utf8');

  if (content.includes('patchElf16KB')) {
    console.log('[fix-expo-gradle] ELF patcher already injected, skipping');
    return;
  }

  // Append the ELF patcher at the end of app/build.gradle
  const alignmentBlock = `

// ============================================================
// 16KB Page Size ELF Patcher — Pure Groovy, doLast injection
// Rewrites p_align in ELF64 PT_LOAD segments from 4096 → 16384.
// Injected via doLast on merge + strip tasks.
// ============================================================
afterEvaluate {
    def patchElf16KB = { String taskDisplayName ->
        def readUShort = { byte[] buf, int off ->
            (buf[off] & 0xFF) | ((buf[off+1] & 0xFF) << 8)
        }
        def readLong = { byte[] buf, int off ->
            long v = 0
            for (int i = 7; i >= 0; i--) { v = (v << 8) | (buf[off + i] & 0xFFL) }
            return v
        }
        def writeLong = { byte[] buf, int off, long val ->
            for (int i = 0; i < 8; i++) { buf[off + i] = (byte)(val & 0xFF); val >>= 8 }
        }
        def searchDirs = [
            file("\\\${buildDir}/intermediates/merged_jni_libs"),
            file("\\\${buildDir}/intermediates/merged_native_libs"),
            file("\\\${buildDir}/intermediates/stripped_native_libs"),
            file("\\\${buildDir}/intermediates/transforms"),
            file("\\\${buildDir}/intermediates/merged_jni_libs/release"),
            file("\\\${buildDir}/intermediates/merged_native_libs/release"),
            file("\\\${buildDir}/intermediates/stripped_native_libs/release"),
        ]
        int totalFixed = 0
        int totalSkipped = 0
        searchDirs.each { dir ->
            if (!dir.exists()) return
            fileTree(dir: dir, include: ['**/arm64-v8a/*.so', '**/x86_64/*.so']).each { soFile ->
                try {
                    def raf = new RandomAccessFile(soFile, "rw")
                    try {
                        def ident = new byte[64]
                        raf.readFully(ident)
                        if (ident[0] != 0x7F || ident[1] != 0x45 || ident[2] != 0x4C || ident[3] != 0x46) return
                        if (ident[4] != 2) return
                        long e_phoff = readLong(ident, 32)
                        int e_phentsize = readUShort(ident, 54)
                        int e_phnum = readUShort(ident, 56)
                        if (e_phoff == 0 || e_phnum == 0) return
                        boolean modified = false
                        for (int i = 0; i < e_phnum; i++) {
                            long phOffset = e_phoff + ((long)i * e_phentsize)
                            def phdr = new byte[e_phentsize]
                            raf.seek(phOffset)
                            raf.readFully(phdr)
                            int p_type = (phdr[0] & 0xFF) | ((phdr[1] & 0xFF) << 8) |
                                         ((phdr[2] & 0xFF) << 16) | ((phdr[3] & 0xFF) << 24)
                            if (p_type != 1) continue
                            long p_offset = readLong(phdr, 8)
                            long p_vaddr  = readLong(phdr, 16)
                            long p_align  = readLong(phdr, 48)
                            if (p_align >= 16384L) continue
                            long offMod = p_offset % 16384L
                            long vaddrMod = p_vaddr % 16384L
                            if (offMod == vaddrMod) {
                                raf.seek(phOffset + 48)
                                def buf = new byte[8]
                                writeLong(buf, 0, 16384L)
                                raf.write(buf)
                                modified = true
                            } else {
                                totalSkipped++
                                logger.warn "[16KB] SKIP \\\${soFile.name} seg \\\${i}: off%16K=\\\${offMod} vaddr%16K=\\\${vaddrMod}"
                            }
                        }
                        if (modified) {
                            totalFixed++
                            logger.lifecycle "[16KB] PATCHED \\\${soFile.absolutePath}"
                        }
                    } finally { raf.close() }
                } catch (Exception e) {
                    logger.warn "[16KB] ERROR \\\${soFile.name}: \\\${e.message}"
                }
            }
        }
        logger.lifecycle "[16KB] \\\${taskDisplayName}: patched=\\\${totalFixed}, skipped=\\\${totalSkipped}"
    }
    tasks.withType(Task) { task ->
        def name = task.name
        if (name.contains("merge") && (name.contains("JniLib") || name.contains("NativeLib"))) {
            task.doLast {
                logger.lifecycle "[16KB] >>> Patching after \\\${name}"
                patchElf16KB(name)
            }
        }
        if (name.contains("strip") && (name.contains("Native") || name.contains("Debug") || name.contains("Symbol"))) {
            task.doLast {
                logger.lifecycle "[16KB] >>> Patching after \\\${name}"
                patchElf16KB(name)
            }
        }
    }
    tasks.register("patch16KBVerify") {
        doLast {
            logger.lifecycle "[16KB] Running standalone ELF verification..."
            patchElf16KB("patch16KBVerify")
        }
    }
}
`;

  content += alignmentBlock;
  fs.writeFileSync(filePath, content, 'utf8');
  console.log('[fix-expo-gradle] Injected doLast ELF patcher into', filePath);
}
